#!/usr/bin/env python3
"""Assemble the verified bibliography, statement ledger, and delivery archive.

Run --bibliography before LuaLaTeX; run --ledger after the final LuaLaTeX pass;
run --package only after PDF inspection. No mathematical claim is generated by
this script: the ledger copies the actual numbered statements from the sources.
"""
from pathlib import Path
import argparse
import collections
import csv
import hashlib
import json
import re
import zipfile

ROOT = Path(__file__).resolve().parents[1]
ENVS = 'theorem|proposition|lemma|corollary|definition|example|remark|question'


def bib_entries(text):
    starts = list(re.finditer(r'(?m)^@\w+\{([^,]+),', text))
    for i, match in enumerate(starts):
        stop = starts[i + 1].start() if i + 1 < len(starts) else len(text)
        yield match.group(1), text[match.start():stop].strip()


def bibliography():
    # The combined Hatcher record preserves verified locations from both audits.
    existing = dict(bib_entries((ROOT/'TOTASPH_references.bib').read_text()))
    combined = {}
    for name in ['root_references.bib', 'AG_references.bib',
                 'CD_references.bib', 'F_references.bib']:
        for key, entry in bib_entries((ROOT/'research'/name).read_text()):
            if key in combined:
                assert key == 'Hatcher2002', ('Unexpected duplicate', key)
                combined[key] = existing[key]
            else:
                combined[key] = entry
    for key, entry in combined.items():
        assert re.search(r'note\s*=\s*\{(?:verified|unverified)', entry, re.I), key
    (ROOT/'TOTASPH_references.bib').write_text('\n\n'.join(combined.values())+'\n')
    print(json.dumps({'bibliography_entries': len(combined),
                      'verified': sum(bool(re.search(r'note\s*=\s*\{verified', x, re.I))
                                      for x in combined.values()),
                      'unverified': sum(bool(re.search(r'note\s*=\s*\{unverified', x, re.I))
                                        for x in combined.values())}, indent=2))


def aux_labels():
    aux = (ROOT/'build/TOTASPH_paper.aux').read_text()
    return {m[1]: {'number': m[2], 'page': m[3]}
            for m in re.finditer(r'\\newlabel\{([^}]+)\}\{\{([^}]+)\}\{([^}]+)\}', aux)}


