def ledger():
    labels = aux_labels()
    metadata = {}
    for path in sorted((ROOT/'research').glob('*results.csv')):
        with path.open(newline='') as stream:
            for row in csv.DictReader(stream):
                metadata[row['id']] = row
    master = (ROOT/'TOTASPH_paper.tex').read_text()
    source_paths = [ROOT/(x if x.endswith('.tex') else x+'.tex')
                    for x in re.findall(r'\\input\{([^}]+)\}', master)]
    records, index = [], {}
    start_re = re.compile(r'\\begin\{('+ENVS+r')\}\[(.*?)\]\s*\\label\{([^}]+)\}', re.S)
    # Titles may span source lines; allow arbitrary whitespace before label.
    for path in source_paths:
        source = path.read_text()
        raw_starts = list(re.finditer(r'\\begin\{('+ENVS+r')\}', source))
        starts = list(start_re.finditer(source))
        assert len(starts) == len(raw_starts), ('Missing status or label', path)
        for i, match in enumerate(starts):
            env, title, label = match.group(1, 2, 3)
            assert label in labels, ('Uncompiled statement', label)
            assert label not in index, ('Duplicate statement', label)
            status = re.match(r'(Proved|Refuted|Known|Open)(?:[:,])', title)
            assert status, ('Nonstandard status', label, title)
            status = status[1]
            end = source.index('\\end{'+env+'}', match.end())
            body = source[match.end():end].strip()
            block_end = starts[i+1].start() if i+1 < len(starts) else len(source)
            proof_block = source[match.start():block_end]
            line = source.count('\n', 0, match.start()) + 1
            number, page = labels[label]['number'], labels[label]['page']
            prior = metadata.get(label, {})
            deps = set(re.findall(r'\\(?:eq)?ref\{([^}]+)\}', proof_block))
            # Author-supplied metadata may include an additional explicit citation.
            for dep in prior.get('depends_on', '').split(';'):
                dep = dep.strip()
                if dep in labels:
                    deps.add(dep)
            deps.discard(label)
            resolved_deps = []
            for dep in sorted(deps):
                assert dep in labels, ('Undefined dependency', label, dep)
                resolved_deps.append(labels[dep]['number'])
            citations = set()
            for cite in re.finditer(r'\\cite\w*(?:\[[^\]]*\])*\{([^}]+)\}', proof_block):
                citations.update(x.strip() for x in cite[1].split(','))
            resolved_deps += ['bib:'+x for x in sorted(citations)]
            body = re.sub(r'\\label\{[^}]+\}', '', body)
            body = re.sub(r'\\(?:eq)?ref\{([^}]+)\}',
                          lambda m: labels[m[1]]['number'], body)
            body = re.sub(r'\s+', ' ', body).strip()
            notes = [title, 'source_label='+label,
                     'Statement field preserves LaTeX mathematical notation.']
            if prior.get('notes'):
                notes.append(prior['notes'])
            manuscript = prior.get('manuscript_rows_or_pages_settled', '') or ROOT_ROWS.get(label, '')
            if not manuscript:
                manuscript = 'Part '+number.split('.')[0]+'; supporting statement'
            where = f'TOTASPH_paper.pdf p.{page}; {env.title()} {number}; {path.relative_to(ROOT)}:{line}'
            if status == 'Open':
                where += '; exact unresolved claim and obstruction, not a proof'
            records.append({'id':number, 'statement':body, 'status':status,
                            'where_proved':where, 'depends_on':'; '.join(resolved_deps),
                            'manuscript_rows_or_pages_settled':manuscript,
                            'notes':' '.join(notes)})
            index[label] = {'id':number,'status':status,'environment':env,
                            'title':title,'page':page,'source':str(path.relative_to(ROOT)),
                            'line':line}
    assert len({r['id'] for r in records}) == len(records)
    columns = ['id','statement','status','where_proved','depends_on',
               'manuscript_rows_or_pages_settled','notes']
    with (ROOT/'TOTASPH_results.csv').open('w',newline='') as stream:
        writer = csv.DictWriter(stream, fieldnames=columns)
        writer.writeheader(); writer.writerows(records)
    (ROOT/'research/statement_index.json').write_text(json.dumps(index,indent=2)+'\n')
    print(json.dumps({'numbered_statements':len(records),
                      'status_counts':dict(collections.Counter(r['status'] for r in records)),
                      'open_statements':[r['id'] for r in records if r['status']=='Open'],
                      'all_numbered_statements_included':True},indent=2))


def report():
    records = ['AG_report.md','CD_report.md','CD_followup.md','F_report.md',
               'CD_C048_report.md','AG_general_report.md']
    text = (ROOT/'research/root_report.md').read_text().rstrip()+'\n'
    for i, name in enumerate(records, 1):
        path = ROOT/'research'/name
        assert path.is_file(), name
        source = path.read_text().strip()
        source = re.sub(r'(?m)^(#{1,5}) ', r'##\1 ', source)
        text += '\n---\n\n## Appendix '+str(i)+': '+name+'\n\n'+source+'\n'
    (ROOT/'TOTASPH_report.md').write_text(text)
    print(json.dumps({'report_words':len(text.split()),'audit_appendices':len(records)},indent=2))


def package():
    needed = ['TOTASPH_paper.tex','TOTASPH_paper.pdf','TOTASPH_results.csv',
              'TOTASPH_references.bib','TOTASPH_report.md','README.md']
    for name in needed:
        assert (ROOT/name).is_file(), name
    files = [ROOT/name for name in needed]
    files += sorted((ROOT/'sections').glob('*.tex'))
    files += [p for p in sorted((ROOT/'code').iterdir()) if p.is_file()
              and p.suffix in {'.py','.json','.txt','.out','.log'}]
    files += [p for p in sorted((ROOT/'research').iterdir()) if p.is_file()
              and p.suffix in {'.md','.csv','.bib','.json'}]
    # Full copyrighted article text, TeX caches, and attachment archives are excluded.
    log = ROOT/'code/root_package.out.txt'
    files = sorted(set(files+[log]))
    log.write_text('Packaged files: '+str(len(files))+'\n'+
                   '\n'.join(str(p.relative_to(ROOT)) for p in files)+'\n')
    archive = ROOT.parent/'TOTASPH.zip'
    with zipfile.ZipFile(archive,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=9) as z:
        for path in files:
            z.write(path, 'TOTASPH/'+str(path.relative_to(ROOT)))
    with zipfile.ZipFile(archive) as z:
        assert z.testzip() is None
        assert len(z.namelist()) == len(files)
    print(json.dumps({'zip':str(archive),'files':len(files),
                      'bytes':archive.stat().st_size,
                      'sha256':hashlib.sha256(archive.read_bytes()).hexdigest(),
                      'crc_integrity':'passed'},indent=2))


if __name__ == '__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--bibliography',action='store_true')
    parser.add_argument('--ledger',action='store_true')
    parser.add_argument('--package',action='store_true')
    parser.add_argument('--report',action='store_true')
    args=parser.parse_args()
    if args.bibliography: bibliography()
    if args.ledger: ledger()
    if args.report: report()
    if args.package: package()
