"""Finite searches for faithful positive solutions of the suffix equations.

Every tested length vector satisfies the exact integer equations.
Unit-position identifications give a universal word solution at those lengths.
Stallings folding computes the rank of the subgroup generated by the u_i,v_i.
Equality with 2|V|-|E_closed| proves faithfulness for THIS finite object, using
the independently proved freeness of its coordinate group and Hopficity.
No compatible choices across objects, nor FreeMon diagram, are asserted.
AI-produced, GPT-6 Astra, ChatGPT Pro, 17 November 2026.
"""

import argparse
import json
import math
import random
from pathlib import Path

import sympy as sp


class DSU:
    def __init__(self, n=0):
        self.p = list(range(n))
        self.sz = [1] * n

    def add(self):
        v = len(self.p)
        self.p.append(v)
        self.sz.append(1)
        return v

    def find(self, x):
        while self.p[x] != x:
            self.p[x] = self.p[self.p[x]]
            x = self.p[x]
        return x

    def union(self, x, y):
        x, y = self.find(x), self.find(y)
        if x == y:
            return False
        if self.sz[x] < self.sz[y]:
            x, y = y, x
        self.p[y] = x
        self.sz[x] += self.sz[y]
        return True


def validate(n, edges):
    masks = [sum(1 << x for x in e) for e in edges]
    delta = [2 * m.bit_count() - 3 * sum(m & e == e for e in masks)
             for m in range(1 << n)]
    assert min(delta[1:]) > 0, (n, edges)
    actual = [e for e, mask in zip(edges, masks)
              if all(delta[m] > 3 for m in range(1 << n)
                     if m != mask and m & mask == mask)]
    return actual


def kernel(n, edges):
    rows = []
    for a, b, c in edges:
        row = [0] * (2 * n)
        row[b] += 1
        row[a] -= 1
        row[n + c] += 1
        row[n + a] -= 1
        rows.append(row)
    mat = sp.Matrix(rows) if rows else sp.zeros(0, 2 * n)
    assert mat.rank() == len(edges)
    out = []
    for v in mat.nullspace():
        denominator = sp.ilcm(*[x.q for x in v])
        out.append([int(x * denominator) for x in v])
    return out


def length_vector(n, edges, kbasis, rng, spread):
    coefficients = [rng.randint(-spread, spread) for _ in kbasis]
    perturbation = [sum(c * v[i] for c, v in zip(coefficients, kbasis))
                    for i in range(2 * n)]
    margin = 1 + max([abs(x) for x in perturbation] +
                     [abs(perturbation[n + a] - perturbation[b])
                      for a, b, c in edges])
    u = [margin + x for x in perturbation[:n]]
    v = [2 * margin + x for x in perturbation[n:]]
    t = [v[a] - u[b] for a, b, c in edges]
    assert min(u + v + t) > 0
    for k, (a, b, c) in enumerate(edges):
        assert v[a] == u[b] + t[k]
        assert v[c] == u[a] + t[k]
    return u, v, t


def universal_words(lengths, edges):
    ulen, vlen, tlen = lengths
    dsu = DSU()

    def newword(length):
        return [dsu.add() for _ in range(length)]

    u = [newword(k) for k in ulen]
    v = [newword(k) for k in vlen]
    t = [newword(k) for k in tlen]
    for k, (a, b, c) in enumerate(edges):
        for p, q in zip(v[a], u[b] + t[k]):
            dsu.union(p, q)
        for p, q in zip(v[c], u[a] + t[k]):
            dsu.union(p, q)
    letters = {root: i + 1 for i, root in enumerate(
        sorted({dsu.find(x) for x in range(len(dsu.p))}))}
    image = lambda w: [letters[dsu.find(x)] for x in w]
    u, v, t = ([image(w) for w in ws] for ws in (u, v, t))
    for k, (a, b, c) in enumerate(edges):
        assert v[a] == u[b] + t[k]
        assert v[c] == u[a] + t[k]
    return u, v, t, len(letters)


def subgroup_rank(words, positive_markings=()):
    vertices = DSU(1)
    edges = []
    for word in words:
        start = 0
        for i, label in enumerate(word):
            end = 0 if i == len(word) - 1 else vertices.add()
            edges.append((start, label, end))
            start = end
    while True:
        destinations = {}
        changed = False
        for start, label, end in edges:
            for x, a, y in ((start, label, end), (end, -label, start)):
                key = (vertices.find(x), a)
                target = vertices.find(y)
                if key in destinations:
                    changed |= vertices.union(target, destinations[key])
                else:
                    destinations[key] = target
        if not changed:
            break
    normalized = {(vertices.find(s), a, vertices.find(t))
                  for s, a, t in edges}
    used = {0}
    for s, a, t in normalized:
        used.add(s)
        used.add(t)
    used = {vertices.find(x) for x in used}
    rank = len(normalized) - len(used) + 1
    if not positive_markings:
        return rank
    normalized = sorted(normalized)
    adjacency = {v: [] for v in used}
    for i, (s, a, t) in enumerate(normalized):
        adjacency[s].append((t, i))
        adjacency[t].append((s, i))
    base = vertices.find(0)
    seen, pending, tree = {base}, [base], set()
    while pending:
        s = pending.pop()
        for t, i in adjacency[s]:
            if t not in seen:
                seen.add(t)
                pending.append(t)
                tree.add(i)
    generators = {i: j + 1 for j, i in enumerate(
        i for i in range(len(normalized)) if i not in tree)}
    assert len(generators) == rank
    next_edge = {(s, a): (t, i) for i, (s, a, t) in enumerate(normalized)}
    collapsed = []
    for word in positive_markings:
        vertex, output = base, []
        for letter in word:
            vertex, edge_id = next_edge[(vertex, letter)]
            if edge_id in generators:
                output.append(generators[edge_id])
        assert vertex == base
        collapsed.append(output)
    return rank, collapsed


EXAMPLES = [
    ("single", 3, [(0, 1, 2)]),
    ("common_first", 5, [(0, 1, 4), (0, 2, 3)]),
    ("common_middle", 5, [(0, 2, 4), (1, 2, 3)]),
    ("common_last", 5, [(0, 1, 4), (2, 3, 4)]),
    ("loose_path", 7, [(0, 1, 2), (2, 3, 4), (4, 5, 6)]),
    ("loose_four_cycle", 8, [(0, 1, 2), (2, 3, 4), (4, 5, 6), (0, 6, 7)]),
    ("ratio_obstruction", 13,
     [(0, 4, 5), (0, 1, 9), (1, 2, 10), (2, 3, 11),
      (3, 4, 12), (5, 6, 7), (7, 8, 9)]),
]


def run(trials, spread, seed, destination):
    rng = random.Random(seed)
    results = []
    for name, n, all_edges in EXAMPLES:
        edges = validate(n, all_edges)
        assert len(edges) == len(all_edges)
        kbasis = kernel(n, edges)
        target_rank = 2 * n - len(edges)
        best = None
        observed = set()
        for trial in range(trials):
            lengths = length_vector(n, edges, kbasis, rng, spread)
            u, v, t, alphabet_size = universal_words(lengths, edges)
            rank, chart = subgroup_rank(u + v, u + v + t)
            assert rank <= target_rank, (name, rank, target_rank)
            observed.add(rank)
            candidate = dict(trial=trial, rank=rank, alphabet_size=alphabet_size,
                             lengths=lengths, u=u, v=v, t=t,
                             positive_basis_chart=chart)
            if best is None or rank > best["rank"]:
                best = candidate
            if rank == target_rank:
                break
        result = dict(name=name, vertices=n, edges=edges, expected_rank=target_rank,
                      observed_ranks=sorted(observed), best=best,
                      faithful=best["rank"] == target_rank)
        results.append(result)
        print(f"{name}: target rank {target_rank}, best {best['rank']}, "
              f"trials {trial + 1}, alphabet {best['alphabet_size']}, "
              f"faithful finite solution {result['faithful']}", flush=True)
    Path(destination).write_text(json.dumps(results, indent=2) + "\n")
    print("Individual finite solutions only. No functorial lift or C_delta comparison claim.")


