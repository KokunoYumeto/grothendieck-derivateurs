"""Check the finite all-truncations strict-composition counterexample.
Input: the independently certified ten-element monoid / 52-element right action
from Part A, in main_counterexample_data.json.
"""
from pathlib import Path
import json
from itertools import product
import sys

output_dir=Path(__file__).resolve().parent/'outputs'
base=Path(sys.argv[1]) if len(sys.argv)>1 else output_dir/'main_counterexample_data.json'
data=json.loads(base.read_text(encoding='utf-8'))
M=data['multiplication']; H=data['right_action']; unit=data['identity_index']
m=len(M); h=len(H)
assert m==10 and h==52
for a,b,c in product(range(m),repeat=3): assert M[a][M[b][c]]==M[M[a][b]][c]
for x,a,b in product(range(h),range(m),range(m)):
    assert H[H[x][a]][b]==H[x][M[a][b]]

obs=('L','O','U','T')
arr={}
for a in range(m):
    arr[('LL',a)]=('L','L'); arr[('UU',a)]=('U','U'); arr[('LU',a)]=('L','U')
arr[('OO',0)]=('O','O'); arr[('TT',0)]=('T','T')
arr[('OU',0)]=('O','U'); arr[('OT',0)]=('O','T')
for x in range(h):
    arr[('LT',x)]=('L','T'); arr[('UT',x)]=('U','T')
ids={'L':('LL',unit),'U':('UU',unit),'O':('OO',0),'T':('TT',0)}

def comp(g,f):
    assert arr[f][1]==arr[g][0]
    if f==ids[arr[f][0]]: return g
    if g==ids[arr[g][1]]: return f
    fg,gg=f[0],g[0]
    if fg in ('LL','UU','LU') and gg in ('LL','UU','LU'):
        return (arr[f][0]+arr[g][1],M[g[1]][f[1]])
    if fg=='OU' and gg=='UU': return ('OU',0)
    if gg in ('LT','UT') and fg in ('LL','UU','LU'):
        return (arr[f][0]+'T',H[g[1]][f[1]])
    if fg=='OU' and gg=='UT': return ('OT',0)
    raise AssertionError((g,f))

for f,(s,t) in arr.items():
    assert comp(f,ids[s])==f and comp(ids[t],f)==f
pairs=0; triples=0
for g,f in product(arr,repeat=2):
    if arr[f][1]!=arr[g][0]: continue
    c=comp(g,f); pairs+=1
    assert arr[c]==(arr[f][0],arr[g][1])
    for k in arr:
        if arr[g][1]!=arr[k][0]: continue
        assert comp(k,c)==comp(comp(k,g),f); triples+=1

Xobs={'L','O','U'}; Xarr={f:st for f,st in arr.items() if st[0] in Xobs and st[1] in Xobs}
for S in ({'L'},Xobs):
    assert all(s in S for s,t in arr.values() if t in S)
# The cosieve generated by L in X is exactly {L,U}.
assert {t for s,t in Xarr.values() if s=='L'}=={'L','U'}
# Right adjoint on that cosieve forgets the L/U copy and preserves the M label.
for a in range(m):
    for b in range(m):
        assert comp(('UU',a),('LU',b))==('LU',M[a][b])
        assert comp(('LU',a),('LL',b))==('LU',M[a][b])
for w in ('L','U'):
    counit=('LL',unit) if w=='L' else ('LU',unit)
    images={comp(counit,('LL',a)) for a in range(m)}
    target={f for f,(s,t) in Xarr.items() if s=='L' and t==w}
    assert images==target
# Composite's crossing presheaf at T is exactly the original right M-set H.
for x,a in product(range(h),range(m)):
    assert comp(('LT',x),('LL',a))==('LT',H[x][a])
    assert comp(('UT',x),('LU',a))==('LT',H[x][a])
    assert comp(('UT',x),('UU',a))==('UT',H[x][a])
    assert comp(('UT',x),('OU',0))==('OT',0)
report=json.dumps({'input_file':base.name,'monoid_size':m,'right_set_size':h,
    'X_objects':len(Xobs),'X_arrows':len(Xarr),'Y_objects':len(obs),'Y_arrows':len(arr),
    'composable_pairs_checked':pairs,'associativity_triples_checked':triples,
    'identity_and_typing_checks':True,'both_inclusions_are_sieves':True,
    'first_inclusion_Dwyer_right_adjoint_checked':True,
    'second_inclusion_crossing_presheaf_is_G':True,
    'composite_crossing_presheaf_at_t_is_original_H':True,
    'universal_totality_basis':'Analytic proof via Kan extension and restricted-action criterion; not finite testing of p.'},indent=2)
output_dir.mkdir(parents=True,exist_ok=True)
(output_dir/'check_truncated_composition.out').write_text(report+'\n',encoding='utf-8')
print(report)
