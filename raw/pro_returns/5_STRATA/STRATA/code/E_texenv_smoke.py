"""Exercise the paper's actual preamble, all fonts, and APA/natbib citations."""
from pathlib import Path
from E_texenv import PROJECT, ROOT, run

directory = ROOT / "smoke"
directory.mkdir(parents=True, exist_ok=True)
preamble = (PROJECT / "STRATA_paper.tex").read_text().split(r"\begin{document}")[0]
preamble = preamble.replace(r"\usepackage[round,authoryear]{natbib}",
                            r"\usepackage[natbibapa]{apacite}")
body = r"""
\begin{document}
\maketitle
\section{LuaLaTeX and APA verification}
The actual paper preamble is used above. All output is generated by
LuaHBTeX with the local LuaLaTeX format. We retain accents such as
préfaisceaux, Grothendieck's apostrophe, and ordinary typographic dashes.
\begin{statement}{T.1}{Proved}{Fonts and packages}
The mathematical fonts, theorem font, hyperlinks, and tabular packages load.
\end{statement}
\begin{proof}
We exercise $\mathbb D$, $\mathscr F$, $\mathbf{Cat}$, $\alpha^*$,
$\varnothing$, $\xrightarrow{\simeq}$ and
\[
 \Hom_X^{\beta\alpha}(x,z)
 \cong\Hom_{X_s}(x,\alpha^*\beta^*z)
 \cong\Hom_{X_t}(\alpha_!x,\beta^*z).
\]
The result is cited narratively by \citet[Theorem 5.3.14]{Cisinski2006}
and parenthetically \citep[Theorem 1.2]{Thomason1979}.
\end{proof}
\begin{center}
\begin{tabular}{ll}
\toprule
Feature & Result\\
\midrule
\texttt{fontspec}, \texttt{microtype} & Roman, bold, and \textit{italic}\\
\texttt{mathtools}, \texttt{amssymb} & $\mathbb S,\mathcal C,\subseteq,\colim$\\
\texttt{hyperref}, \texttt{bookmark} & \url{https://www.numdam.org/}\\
\bottomrule
\end{tabular}
\end{center}
\bibliographystyle{apacite}
\bibliography{smoke}
\end{document}
"""
(directory / "smoke.tex").write_text(preamble + body)
(directory / "smoke.bib").write_text(r"""
@book{Cisinski2006,
 author={Cisinski, Denis-Charles},
 title={Les préfaisceaux comme modèles des types d'homotopie},
 year={2006}, volume={308}, series={Astérisque},
 publisher={Société Mathématique de France},
 note={verified: source opened, Theorem 5.3.14}
}
@article{Thomason1979,
 author={Thomason, Robert W.},
 title={Homotopy colimits in the category of small categories},
 journal={Mathematical Proceedings of the Cambridge Philosophical Society},
 volume={85}, number={1}, pages={91--109}, year={1979},
 doi={10.1017/S0305004100055535},
 note={unverified: build test bibliographic example}
}
""")
for command in [
    ["lualatex", "-interaction=nonstopmode", "-halt-on-error", "smoke.tex"],
    ["bibtex", "smoke"],
    ["lualatex", "-interaction=nonstopmode", "-halt-on-error", "smoke.tex"],
    ["lualatex", "-interaction=nonstopmode", "-halt-on-error", "smoke.tex"],
]:
    run(command, directory)
log = (directory / "smoke.log").read_text()
prohibited = [
    "LaTeX Error:", "Undefined control sequence", "Missing character:",
    "There were undefined citations", "There were undefined references",
]
errors = [marker for marker in prohibited if marker in log]
if errors:
    raise RuntimeError("Final smoke log contains: " + ", ".join(errors))
run(["pdfinfo", "smoke.pdf"], directory)
run(["pdffonts", "smoke.pdf"], directory)
print("PASS: actual preamble, mathematical fonts, and APA natbib citations.")
