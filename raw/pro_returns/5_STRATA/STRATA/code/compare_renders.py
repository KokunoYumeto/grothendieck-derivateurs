"""Compare two Poppler page-render directories exactly.

Usage: python3 code/compare_renders.py OLD_DIRECTORY NEW_DIRECTORY
Both directories are generated by pdf_qa.py. This lets a visual review
transfer only when the rendered page image is byte-for-byte identical.
Changed pages always require a fresh visual inspection.
"""
from pathlib import Path
import argparse
import hashlib
import json

parser = argparse.ArgumentParser()
parser.add_argument('old_directory', type=Path)
parser.add_argument('new_directory', type=Path)
args = parser.parse_args()

def page_map(directory):
    result = {}
    for path in directory.glob('page-*.png'):
        number = int(path.stem.split('-')[-1])
        result[number] = hashlib.sha256(path.read_bytes()).hexdigest()
    assert result, str(directory)
    return result

old = page_map(args.old_directory)
new = page_map(args.new_directory)
assert set(old) == set(new), (sorted(set(old) - set(new)),
                             sorted(set(new) - set(old)))
unchanged = sorted(number for number in new if new[number] == old[number])
changed = sorted(set(new) - set(unchanged))
print(json.dumps({'old_render_directory': str(args.old_directory),
                  'new_render_directory': str(args.new_directory),
                  'page_count': len(new),
                  'identical_page_images': unchanged,
                  'changed_page_images': changed}, indent=2))
